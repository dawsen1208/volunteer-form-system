export function getMajorCatalog(type: FormType): MajorCatalog {
  return type === "undergrad" ? undergradMajorCatalog : juniorMajorCatalog;
}

export function findMajorCategoryByName(type: FormType, majorName: string): string | undefined {
  const name = String(majorName ?? "").trim();
  if (!name) return undefined;
  const catalog = getMajorCatalog(type);
  for (const [cat, majors] of Object.entries(catalog)) {
    if (majors.includes(name)) return cat;
  }
  return undefined;
}

export function getMajorNameOptions(type: FormType, category?: string) {
  const catalog = getMajorCatalog(type);
  const cat = String(category ?? "").trim();
  if (cat && Array.isArray(catalog[cat])) {
    return (catalog[cat] ?? []).map((m) => ({ label: m, value: m }));
  }
  const options: Array<{ label: string; value: string }> = [];
  for (const [c, majors] of Object.entries(catalog)) {
    for (const m of majors) {
      options.push({ label: `${m}（${c}）`, value: m });
    }
  }
  return options;
}

export function isMajorInCategory(type: FormType, category: string, majorName: string): boolean {
  const catalog = getMajorCatalog(type);
  const cat = String(category ?? "").trim();
  const name = String(majorName ?? "").trim();
  if (!cat || !name) return false;
  const majors = catalog[cat];
  return Array.isArray(majors) ? majors.includes(name) : false;
}
